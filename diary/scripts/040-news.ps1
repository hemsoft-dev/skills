#!/usr/bin/env pwsh
<#
.SYNOPSIS
    Fills the News Headlines section of a diary entry.

.DESCRIPTION
    Reads the news output file generated by the news skill's Get-AllNews.ps1,
    and injects it into the diary entry. Runs Get-AllNews.ps1 first if no
    output exists for the given date.

.PARAMETER Date
    The date for the diary entry in yyyy-MM-dd format. Defaults to today.

.PARAMETER EntryPath
    The full path to the diary entry file to update.

.EXAMPLE
    .\040-news.ps1 -Date 2026-02-28 -EntryPath ..\entries\2026-02-28.md
#>

[CmdletBinding()]
param(
    [string]$Date = (Get-Date -Format 'yyyy-MM-dd'),
    [string]$EntryPath
)

$ErrorActionPreference = 'Stop'
$InformationPreference = 'Continue'

# --- Resolve entry path ---
if (-not $EntryPath) {
    $EntryPath = Join-Path $PSScriptRoot '..' 'entries' "$Date.md"
}

if (-not (Test-Path $EntryPath)) {
    Write-Error "Diary entry not found: $EntryPath"
    exit 1
}

# --- Locate news output ---
$newsOutputDir = Join-Path $env:USERPROFILE '.agents' 'skills' 'news' 'output'
$newsFile = Join-Path $newsOutputDir "$Date.md"

if (-not (Test-Path $newsFile)) {
    # Try to generate it
    $allNewsScript = Join-Path $env:USERPROFILE '.agents' 'skills' 'news' 'scripts' 'Get-AllNews.ps1'
    if (Test-Path $allNewsScript) {
        Write-Information "`e[1;33mNews output not found for $Date. Generating...`e[0m"
        & $allNewsScript 6>&1 | Out-Null
    }

    if (-not (Test-Path $newsFile)) {
        Write-Information "`e[1;31mNo news output available for $Date. Skipping.`e[0m"
        return
    }
}

# --- Read the news output ---
$newsContent = (Get-Content $newsFile -Raw).Trim()

if (-not $newsContent) {
    Write-Information "`e[1;31mNews output file is empty for $Date. Skipping.`e[0m"
    return
}

Write-Information "`e[1;36mInjecting news headlines into diary entry...`e[0m"

# --- Count headlines for reporting ---
$headlineCount = ([regex]::Matches($newsContent, '^\|\s*\d+\s*\|', 'Multiline')).Count
$categoryCount = ([regex]::Matches($newsContent, '^###\s+', 'Multiline')).Count

# --- Inject into diary entry ---
$entry = Get-Content $EntryPath -Raw

# Match the News Headlines section between the header and the next "---" divider
# The header format is: ## 📰 News Headlines (Month Day, Year)
$sectionPattern = '(#{2,3}\s+📰\s+News Headlines\s*\([^)]*\)\s*\r?\n)([\s\S]*?)(\r?\n---)'
if ($entry -match $sectionPattern) {
    $entry = $entry -replace $sectionPattern, "`${1}`n$newsContent`n`${3}"
    $utf8NoBom = [System.Text.UTF8Encoding]::new($false)
    [System.IO.File]::WriteAllText($EntryPath, $entry, $utf8NoBom)
    Write-Information "`e[1;32mNews headlines injected into diary entry.`e[0m"
    Write-Information "  Categories: $categoryCount | Headlines: $headlineCount"
}
else {
    Write-Information "`e[1;31mNews Headlines section not found in entry. Cannot inject.`e[0m"
}
